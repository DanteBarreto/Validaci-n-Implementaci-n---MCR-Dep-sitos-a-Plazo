-- Control 20. Unicidad de Operacion por fecha
SELECT 
	CUENTA,
	FECHAPROCESO,
	COUNT(1) AS UniqueFechaProceso
FROM 
	mb_dpf.dbo.mb_dpf_mod
WHERE
	CAPITAL > 0
GROUP BY
	CUENTA,
	FECHAPROCESO
HAVING
	COUNT(1) > 1
ORDER BY
	CUENTA,
	FECHAPROCESO;
GO

