-- 3.1 Distribuci n de tasas de interes en el tiempo
WITH Percentiles AS (
    SELECT 
        FECHAPROCESO,
        TASAINTERES,
		PERCENTILE_CONT(0.01) WITHIN GROUP (ORDER BY TASAINTERES) OVER (PARTITION BY FECHAPROCESO) AS Percentil_01,
		PERCENTILE_CONT(0.05) WITHIN GROUP (ORDER BY TASAINTERES) OVER (PARTITION BY FECHAPROCESO) AS Percentil_05,
        PERCENTILE_CONT(0.10) WITHIN GROUP (ORDER BY TASAINTERES) OVER (PARTITION BY FECHAPROCESO) AS Percentil_10,
        PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY TASAINTERES) OVER (PARTITION BY FECHAPROCESO) AS Percentil_25,
        PERCENTILE_CONT(0.50) WITHIN GROUP (ORDER BY TASAINTERES) OVER (PARTITION BY FECHAPROCESO) AS Percentil_50,
        PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY TASAINTERES) OVER (PARTITION BY FECHAPROCESO) AS Percentil_75,
        PERCENTILE_CONT(0.90) WITHIN GROUP (ORDER BY TASAINTERES) OVER (PARTITION BY FECHAPROCESO) AS Percentil_90,
		PERCENTILE_CONT(0.95) WITHIN GROUP (ORDER BY TASAINTERES) OVER (PARTITION BY FECHAPROCESO) AS Percentil_95,
		PERCENTILE_CONT(0.99) WITHIN GROUP (ORDER BY TASAINTERES) OVER (PARTITION BY FECHAPROCESO) AS Percentil_99
    FROM 
        mb_dpf.dbo.mb_dpf_mod
)
SELECT 
    FECHAPROCESO,
    MIN(TASAINTERES) AS Tasa_minima,
    MAX(TASAINTERES) AS Tasa_maxima,
	AVG(Percentil_01) AS Percentil_01,
	AVG(Percentil_05) AS Percentil_05,
    AVG(Percentil_10) AS Percentil_10,
    AVG(Percentil_25) AS Percentil_25,
    AVG(Percentil_50) AS Percentil_50,
    AVG(Percentil_75) AS Percentil_75,
    AVG(Percentil_90) AS Percentil_90,
	AVG(Percentil_95) AS Percentil_95,
	AVG(Percentil_99) AS Percentil_99
FROM 
    Percentiles
GROUP BY 
    FECHAPROCESO
ORDER BY 
    FECHAPROCESO;
GO

-- 3.2 Tasa de interés con tasa soberana (pre filtros)
WITH CTE AS (
	SELECT 
		CAST(FORMAT(FECHAPROCESO, 'yyyyMM') + '01' AS DATE) AS FECHAPROCESO,
		AVG(TASAINTERES) / 100 AS TASAINTERES
	FROM
		mb_dpf.dbo.mb_dpf_mod
	WHERE
		FECHAPROCESO = FECHAAPERTURA
	GROUP BY
		FORMAT(FECHAPROCESO, 'yyyyMM')
)
SELECT
	A.FECHAPROCESO,
	AVG(A.TASAINTERES) AS TASAINTERES,
	AVG(B.D360) as D360,
	AVG(B.D180) as D180
FROM
	CTE A
INNER JOIN
	[ALS_CONSOLIDADO].[dbo].[Curva_Soberana_SBS_Mensual] B
ON
	A.FECHAPROCESO = B.Mes
WHERE
	A.FECHAPROCESO > '2012-04-01'
GROUP BY
	A.FECHAPROCESO
ORDER BY
	A.FECHAPROCESO;
GO

--3.3 Tasa de interés con tasa soberana por segmento (pre filtros)
WITH CTE AS (
	SELECT 
		CAST(FORMAT(FECHAPROCESO, 'yyyyMM') + '01' AS DATE) AS FECHAPROCESO,
		FLAG,
		AVG(TASAINTERES) / 100 AS TASAINTERES
	FROM
		mb_dpf.dbo.mb_dpf_mod
	WHERE
		FECHAPROCESO = FECHAAPERTURA
	GROUP BY
		FORMAT(FECHAPROCESO, 'yyyyMM'),
		FLAG
)
SELECT
	A.FECHAPROCESO,
	A.FLAG,
	AVG(A.TASAINTERES) AS TASAINTERES,
	AVG(B.D360) as D360,
	AVG(B.D180) as D180
FROM
	CTE A
INNER JOIN
	[ALS_CONSOLIDADO].[dbo].[Curva_Soberana_SBS_Mensual] B
ON
	A.FECHAPROCESO = B.Mes
WHERE
	A.FECHAPROCESO > '2012-04-01'
GROUP BY
	A.FECHAPROCESO,
	A.FLAG
ORDER BY
	A.FECHAPROCESO,
	A.FLAG;
GO

