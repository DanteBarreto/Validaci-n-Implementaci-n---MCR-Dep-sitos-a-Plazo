-- Control 4. Contraste informacion oficial
WITH CTE AS (
    SELECT
        Datos.CODIGO_PRODUCTO,
        Datos.Moneda,
        Datos.FECHAPROCESO,
        CASE
            WHEN Datos.MonedaStr = 'USD' THEN TipoDeCambio.ER
            ELSE 1
        END AS ER,
        Datos.CAPITAL
    FROM
        mb_dpf.dbo.mb_dpf_mod Datos
    LEFT JOIN 
        ALS_CONSOLIDADO.dbo.er TipoDeCambio 
        ON 
            Datos.FECHAPROCESO = TipoDeCambio.Fecha 
            AND Datos.MonedaStr = TipoDeCambio.Moneda
)
SELECT
    FECHAPROCESO,
    SUM(ER * CAPITAL) AS Saldo_Base_SQL
FROM
    CTE
GROUP BY
    FECHAPROCESO
ORDER BY
	FECHAPROCESO;
GO

-- Control 5. Completitud de informacion por operacion
WITH CTE AS (
	SELECT
		CUENTA,
		-- Fecha inicial y final de informacion
		MIN(FECHAPROCESO) AS MinFecha,
		MAX(FECHAPROCESO) AS MaxFecha,
		-- Cantidad de meses de historia
		COUNT(DISTINCT FECHAPROCESO) AS CountFecha
	FROM
		mb_dpf.dbo.mb_dpf_mod
	GROUP BY
		CUENTA
)
SELECT
	*,
	-- Se agrega la cantidad de meses de hsitoria a la fecha inicial
	DATEADD(DAY, CountFecha - 1, MinFecha) AS MaxMesCalculado
FROM
	CTE
WHERE
	DATEADD(MONTH, CountFecha - 1, MinFecha) < MaxFecha;
GO

